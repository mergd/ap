import { describe, test } from "node:test";
import { mkdtemp, readFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { expect } from "./expect.ts";
import { buildAgentGuide, formatGuideHuman } from "../src/guide.ts";
import { rejectRemovedFlags, showToAgentOutput } from "../src/agent-output.ts";
import { yamlStringify } from "../src/yaml.ts";
import { generateSkillMarkdown, installSkill, skillDirs, checkSkillInstallTip } from "../src/skill-install.ts";

describe("ap guide", () => {
  test("buildAgentGuide has required fields", () => {
    const guide = buildAgentGuide();
    expect(guide.version).toBe(5);
    expect(guide.workflow.length > 0).toBe(true);
    expect(guide.rules.prefer_bundle).toBe(true);
    expect(guide.rules.default_secret_scope).toBe("project");
    expect(guide.rules.global_requires_flag).toBe(true);
    expect(guide.commands.show).toContain("ap show");
    expect(guide.commands.catalog).toContain("ap catalog");
    expect(guide.paths.global_manifest).toContain("manifest.toml");
    expect(guide.paths.global_secrets).toBeUndefined();
  });

  test("formatGuideHuman stays succinct", () => {
    const lines = formatGuideHuman().split("\n");
    expect(lines.length).toBeLessThan(20);
    expect(formatGuideHuman()).toContain("ap show <name> --check");
  });

  test("guide serializes to YAML without tables", () => {
    const yaml = yamlStringify(buildAgentGuide());
    expect(yaml).toContain("version: 5");
    expect(yaml).toContain("prefer_bundle: true");
    expect(yaml.includes("never_request_secrets")).toBe(false);
    expect(yaml.includes("| ---")).toBe(false);
  });
});

describe("ap show YAML shape", () => {
  test("includes ready, next, bundles and unbundled secrets without values", () => {
    const out = showToAgentOutput({
      ready: true,
      project: "/repo",
      global_home: "/home/.config/ap",
      bundles: {
        cloudflare: {
          name: "cloudflare",
          ready: true,
          surfaced: [{ key: "CF_EMAIL", value: "user@example.com" }],
          missing: [],
          secrets_set: ["CF_KEY"],
        },
      },
      vars: [
        { key: "CF_EMAIL", scope: "global", storage: "inline", visibility: "public", status: "set", value: "user@example.com" },
        { key: "CF_KEY", scope: "global", storage: "inline", visibility: "secret", status: "set", masked: true },
        { key: "OTHER_TOKEN", scope: "global", storage: "inline", visibility: "secret", status: "set", value: "must-not-show" },
        { key: "MISSING_TOKEN", scope: "global", storage: "inline", visibility: "secret", status: "missing", set_with: "ap set MISSING_TOKEN --global" },
      ],
    });

    expect(out.ready).toBe(true);
    expect(out.bundles!.cloudflare.secrets).toEqual(["CF_KEY"]);
    expect(out.unbundled_secrets!.set).toEqual(["OTHER_TOKEN"]);
    expect(out.unbundled_secrets!.missing).toEqual([
      { key: "MISSING_TOKEN", set_with: "ap set MISSING_TOKEN --global" },
    ]);
    expect(out.next).toBe("ap set MISSING_TOKEN --global");
    expect(JSON.stringify(out).includes("must-not-show")).toBe(false);

    const yaml = yamlStringify(out);
    expect(yaml).toContain("set: [OTHER_TOKEN]");
    expect(yaml).toContain("missing:");
    expect(yaml).toContain("key: MISSING_TOKEN");
  });

  test("includes the next action for a missing bundle secret", () => {
    const out = showToAgentOutput({
      ready: false,
      project: null,
      global_home: "/home/.config/ap",
      bundles: {
        namecheap: {
          name: "namecheap",
          ready: false,
          surfaced: [],
          secrets_set: [],
          missing: [{ key: "NC_API_KEY", set_with: "ap set NC_API_KEY --global" }],
        },
      },
    });

    expect(out.ready).toBe(false);
    expect(out.next).toBe("ap set NC_API_KEY --global");
    expect(out.bundles!.namecheap.next).toBe("ap set NC_API_KEY --global");
    expect(out.bundles!.namecheap.missing![0]!.key).toBe("NC_API_KEY");
  });
});

describe("removed flags", () => {
  test("rejectRemovedFlags errors on --yaml and --json", () => {
    expect(() => rejectRemovedFlags(["show", "--yaml"])).toThrow("--yaml");
    expect(() => rejectRemovedFlags(["show", "--json"])).toThrow("--json");
    expect(() => rejectRemovedFlags(["show", "--human"])).not.toThrow();
    expect(() => rejectRemovedFlags(["set", "KEY", "--unset"])).toThrow("ap unset KEY");
  });
});

describe("skill install generation", () => {
  test("generated SKILL.md covers the agent workflow", () => {
    const md = generateSkillMarkdown();
    expect(md).toContain("generated by ap skill install");
    expect(md).toContain("ap show <bundle> --check");
    expect(md).toContain("ap run <bundle> --");
    expect(md).toContain("ap catalog");
    expect(md).toContain("ap set KEY");
    expect(md.includes("paste secrets")).toBe(false);
  });

  test("skillDirs covers agents, claude, and cursor", () => {
    const project = skillDirs("project", "/repo");
    expect(project.map((l) => l.target)).toEqual(["agents", "claude", "cursor"]);
    expect(project[0]!.dir).toBe("/repo/.agents/skills/ap");
    expect(project[1]!.dir).toBe("/repo/.claude/skills/ap");
    expect(project[2]!.dir).toBe("/repo/.cursor/skills/ap");

    const global = skillDirs("global");
    expect(global[0]!.dir.endsWith("/.agents/skills/ap")).toBe(true);
    expect(global[1]!.dir.endsWith("/.claude/skills/ap")).toBe(true);
    expect(global[2]!.dir.endsWith("/.cursor/skills/ap")).toBe(true);
  });

  test("installSkill writes project skill under repo root", async () => {
    const root = await mkdtemp(join(tmpdir(), "ap-skill-"));
    try {
      const dests = await installSkill("project", { projectRoot: root });
      expect(dests[0]).toBe(join(root, ".agents", "skills", "ap", "SKILL.md"));
      const md = await readFile(dests[0]!, "utf8");
      expect(md).toContain("ap show <bundle> --check");
      expect(await readFile(join(root, ".cursor", "skills", "ap", "SKILL.md"), "utf8")).toContain(
        "ap show <bundle> --check",
      );
    } finally {
      await rm(root, { recursive: true, force: true });
    }
  });

  test("checkSkillInstallTip tips when missing and stays quiet when present", async () => {
    const root = await mkdtemp(join(tmpdir(), "ap-skill-tip-"));
    try {
      const dests = await installSkill("project", { projectRoot: root });
      const installed = dests[0]!;
      const missing = join(root, "nope", "SKILL.md");

      expect(await checkSkillInstallTip({ env: {}, skillPath: missing })).toContain("ap skill install");
      expect(await checkSkillInstallTip({ env: {}, skillPath: installed })).toBe(null);
      expect(await checkSkillInstallTip({ env: { CI: "1" }, skillPath: missing })).toBe(null);
      expect(await checkSkillInstallTip({ env: { AP_NO_SKILL_TIP: "1" }, skillPath: missing })).toBe(
        null,
      );
    } finally {
      await rm(root, { recursive: true, force: true });
    }
  });
});
